#!/usr/bin/env python3
"""Regenerates Families/HitsRow.cs from the staged bench.hits schema.

The POCO insert arm needs a property per column, in table order, with matching CLR types. Writing 105
of those by hand invites exactly one kind of bug — a transposed pair that still compiles — so it is
generated from the table the benchmark actually inserts into.

    ./generate-hits-row.py                       # against http://localhost:8124, database bench
    BENCH_HTTP_URL=... BENCH_DATASET_DB=... ./generate-hits-row.py

Run this only when datasets/01-hits.sql changes. A mismatch between POCO and table is caught at
RegisterBinaryInsertType time, which is a loud failure rather than a wrong number, but a loud failure
in the middle of an overnight run still costs a night.
"""
import os
import pathlib
import sys
import urllib.parse
import urllib.request

URL = os.environ.get("BENCH_HTTP_URL", "http://localhost:8124")
DB = os.environ.get("BENCH_DATASET_DB", "bench")
OUT = pathlib.Path(__file__).resolve().parent.parent / "Families" / "HitsRow.cs"

CLR = {
    "Int16": "short",
    "Int32": "int",
    "Int64": "long",
    "String": "string",
    # Both Date and DateTime decode to System.DateTime (AbstractDateTimeType.FrameworkType).
    "DateTime": "DateTime",
    "Date": "DateTime",
}


def fetch_schema():
    query = (
        "SELECT name, type FROM system.columns "
        f"WHERE database = '{DB}' AND table = 'hits' ORDER BY position FORMAT TSV"
    )
    url = f"{URL}/?" + urllib.parse.urlencode({"query": query})
    raw = urllib.request.urlopen(url, timeout=30).read().decode().strip()
    if not raw:
        sys.exit(
            f"No columns found for {DB}.hits at {URL}. Run scripts/stage-datasets.sh first."
        )

    rows = [line.split("\t") for line in raw.split("\n")]
    unknown = sorted({t for _, t in rows if t not in CLR})
    if unknown:
        sys.exit(f"No CLR mapping for column type(s): {unknown}. Extend CLR in this script.")
    return rows


def render(rows):
    props, assigns, projection, names = [], [], [], []
    for index, (name, ch_type) in enumerate(rows):
        clr = CLR[ch_type]
        props.append(f"    public {clr} {name} {{ get; set; }}")
        names.append(f'        "{name}",')
        projection.append(f"            row.{name},")
        if clr == "string":
            assigns.append(f"            {name} = Text(seed, {index}),")
        elif clr == "DateTime":
            assigns.append(f"            {name} = Timestamp(seed, {index}),")
        else:
            assigns.append(f"            {name} = ({clr})Number(seed, {index}),")

    nl = "\n"
    return f'''// <auto-generated>
// Generated by scripts/generate-hits-row.py from the {DB}.hits schema ({len(rows)} columns, in
// position order). Do not edit by hand: regenerate instead.
// </auto-generated>
using System;

namespace ClickHouse.Driver.Benchmark.Blog.Families;

/// <summary>
/// The {len(rows)}-column ClickBench <c>hits</c> row as a POCO, for the typed insert arm.
/// </summary>
/// <remarks>
/// <para>
/// The point of a full-width POCO rather than a convenient 3-column stand-in: per-value boxing scales
/// with column count, so a 3-column POCO would understate the boxing win by a factor of thirty-five.
/// This is the shape the claim is about.
/// </para>
/// <para>
/// <see cref="Create"/> is deterministic in its seed, and <see cref="ToObjectArray"/> projects the very
/// same instance into the untyped shape — so the POCO arm and the <c>object[]</c> arm insert
/// byte-identical data, and any difference between them is the driver rather than the payload.
/// </para>
/// </remarks>
public sealed class HitsRow
{{
{nl.join(props)}

    /// <summary>Column names in table order, for the <c>object[]</c> insert overload.</summary>
    public static readonly string[] Columns =
    [
{nl.join(names)}
    ];

    /// <summary>Deterministic row for <paramref name="seed"/>. No randomness: two runs insert the same bytes.</summary>
    public static HitsRow Create(int seed) => new()
    {{
{nl.join(assigns)}
    }};

    /// <summary>The same values in table order. Boxes every value type exactly once, by design.</summary>
    public static object[] ToObjectArray(HitsRow row) =>
    [
{nl.join(projection)}
    ];

    /// <summary>
    /// Spreads values across columns so no column is constant (which the server would compress to
    /// nothing) and no column is unique per row (which would let the String columns dominate the wire).
    /// </summary>
    private static long Number(int seed, int column)
    {{
        var mixed = ((long)seed * 6364136223846793005L) + (column * 1442695040888963407L);
        return Math.Abs(mixed % 32749);
    }}

    private static string Text(int seed, int column) =>
        string.Concat("c", column.ToString(), "-", (seed % 997).ToString());

    private static DateTime Timestamp(int seed, int column) =>
        new DateTime(2013, 7, 15, 0, 0, 0, DateTimeKind.Utc).AddSeconds((seed + column) % 2592000);
}}
'''


def main():
    rows = fetch_schema()
    OUT.write_text(render(rows))
    histogram = {}
    for _, t in rows:
        histogram[t] = histogram.get(t, 0) + 1
    print(f"wrote {OUT} ({len(rows)} properties)")
    for t, n in sorted(histogram.items(), key=lambda kv: -kv[1]):
        print(f"  {n:3d}  {t}")


if __name__ == "__main__":
    main()
