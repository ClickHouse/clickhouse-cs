        yield return Dense("CreateArray/QBit", "Array(QBit(Float32, 3))", new[] { Floats(3, 1), Floats(3, 2), Floats(3, 3), Floats(3, 4), Floats(3, 5) }, offsets);
        yield return Dense("CreateArray/Guid into String", "Array(String)", new[] { Guid.Empty, Guid.Empty, Guid.Empty, Guid.Empty, Guid.Empty }, offsets);
        yield return new PinCase("CreateArray/Array(Int32)", "Array(Array(Int32))", 1, () => Task.FromResult<IColumn>(
            ClickHouseTcpColumn.CreateArray("c", ClickHouseTcpColumn.CreateArray("c", ClickHouseTcpColumn.Create("c", new[] { 1, 2, 3, 4, 5 }), offsets), new[] { 0, 1, 1, 4 })));
        yield return new PinCase("CreateArray/Array(Nullable(String))", "Array(Array(Nullable(String)))", 2, () => Task.FromResult<IColumn>(
            ClickHouseTcpColumn.CreateArray("c", ClickHouseTcpColumn.CreateArray("c", ClickHouseTcpColumn.Create("c", new[] { "a", null, "c", "d", null }), offsets), new[] { 0, 1, 1, 4 })));
        yield return DecodedDense<int?, int?>("CreateArray/decoded Nullable(Int32)", "Array(Nullable(Int32))", "Nullable(Int32)", new int?[] { 1, null, 3, null, 5 }, offsets);
        yield return DecodedDense<byte[], string>("CreateArray/decoded String", "Array(String)", "String", new[] { new byte[] { 0xFF }, new byte[] { 0x41 }, Array.Empty<byte>(), new byte[] { 0x42 }, new byte[] { 0x43 } }, offsets);
        yield return DecodedDense<string, string>("CreateArray/decoded LowCardinality(String)", "Array(LowCardinality(String))", "LowCardinality(String)", new[] { "x", "y", "x", "z", "y" }, offsets);
        yield return DecodedDense<int, int>("CreateArray/decoded Int32", "Array(Int32)", "Int32", new[] { 1, 2, 3, 4, 5 }, offsets);
        yield return DecodedDense<uint, uint>("CreateArray/decoded DateTime('UTC') into DateTime", "Array(DateTime)", "DateTime('UTC')", new uint[] { 1, 2, 3, 4, 5 }, offsets);
        yield return DecodedDense<int, int>("CreateArray/decoded Int32 into Int64", "Array(Int64)", "Int32", new[] { 1, 2, 3, 4, 5 }, offsets);

        // Columns of no single CLR type.
        yield return new PinCase("TwoTyped/String", "String", 1, () => Task.FromResult<IColumn>(new TextAndInt()));
        yield return new PinCase("TwoTyped/Int32", "Int32", 1, () => Task.FromResult<IColumn>(new TextAndInt()));
        yield return new PinCase("TwoTyped/UInt8", "UInt8", 1, () => Task.FromResult<IColumn>(new TextAndInt()));
        yield return new PinCase("TwoTyped/DateTime from DateTimeOffset", "DateTime('UTC')", 1, () => Task.FromResult<IColumn>(new InstantAndText(new[] { instant, DateTimeOffset.UnixEpoch })));
        yield return new PinCase("TwoTyped/DateTime from both", "DateTime('UTC')", 1, () => Task.FromResult<IColumn>(new DateTimeAndInstant(new[] { DateTime.UnixEpoch, DateTime.UnixEpoch }, new[] { instant, instant })));
        yield return new PinCase("TwoTyped/Nullable(Int32)", "Nullable(Int32)", 1, () => Task.FromResult<IColumn>(new NullableIntAndText()));
        yield return new PinCase("TwoTyped/FixedString(1)", "FixedString(1)", 1, () => Task.FromResult<IColumn>(new TextAndInt()));
        yield return new PinCase("Untyped/Int32", "Int32", 1, () => Task.FromResult<IColumn>(new UntypedColumn()));
    }

    private static PinCase Of<T>(string name, string type, T[] values)
        => new(name, type, values.Length > 2 ? 2 : 1, () => Task.FromResult<IColumn>(ClickHouseTcpColumn.Create("c", values)));

    private static PinCase Dense<T>(string name, string type, T[] inner, int[] offsets)
        => new(name, type, 2, () => Task.FromResult<IColumn>(ClickHouseTcpColumn.CreateArray("c", ClickHouseTcpColumn.Create("c", inner), offsets)));

    // CreateArray over a column that a query of the inner type read.
    private static PinCase DecodedDense<TWrite, TElement>(string name, string type, string innerType, TWrite[] inner, int[] offsets)
        => new(name, type, 1, async () => ClickHouseTcpColumn.CreateArray("c", (IColumn<TElement>)await DecodeAsync(innerType, inner), offsets));

    // Reads the bytes of the derived write of the values, as a query reads a column.
    private static async Task<IColumn> DecodeAsync<T>(string type, T[] values)
    {
        byte[] bytes = await ConverterHarness.WriteNewAsync(ConverterDerivation.Default.Writer<T>(type, ConverterHarness.Context), values, 0, values.Length);
        IColumnCodec codec = ConverterHarness.Codec(type);
        using ClickHouseBinaryReader reader = CodecTestHarness.ReaderOver(bytes);
        await codec.ReadStatePrefixAsync(reader, CodecTestHarness.None);
        return await codec.ReadColumnAsync(reader, "c", type, values.Length, CodecTestHarness.None);
    }

    private static KeyValuePair<string, int>[] Pairs(params (string Key, int Value)[] pairs)
        => Array.ConvertAll(pairs, pair => new KeyValuePair<string, int>(pair.Key, pair.Value));

    private static float[] Floats(int count, float first) => Enumerable.Range(0, count).Select(i => first * (i + 1) * (i % 2 == 0 ? 1 : -1)).ToArray();

    private static double[] Doubles(int count, double first) => Enumerable.Range(0, count).Select(i => first * (i + 1) * (i % 2 == 0 ? 1 : -1)).ToArray();

    private sealed record PinCase(string Name, string Type, int Start, Func<Task<IColumn>> Column);

    // A column that implements IColumn<> twice, so it has no single element type. GetValue gives the first values.
    private abstract class TwoTypedColumn<T1, T2> : IColumn<T1>
    {
        private readonly T1[] first;

        protected TwoTypedColumn(T1[] first, T2[] second)
        {
            this.first = first;
            Second = second;
        }

        public string Name => "c";

        public string TypeName => null;

        public int RowCount => first.Length;

        public ReadOnlySpan<T1> Values => first;

        protected T2[] Second { get; }

        public T1 this[int row] => first[row];

        public object GetValue(int row) => first[row];

        public void Dispose()
        {
        }
    }

    private sealed class TextAndInt : TwoTypedColumn<string, int>, IColumn<int>
    {
        public TextAndInt()
            : base(new[] { "a", "b" }, new[] { 1, 2 })
        {
        }

        ReadOnlySpan<int> IColumn<int>.Values => Second;

        int IColumn<int>.this[int row] => Second[row];
    }

    private sealed class InstantAndText : TwoTypedColumn<DateTimeOffset, string>, IColumn<string>
    {
        public InstantAndText(DateTimeOffset[] instants)
            : base(instants, new[] { "a", "b" })
        {
        }

        ReadOnlySpan<string> IColumn<string>.Values => Second;

        string IColumn<string>.this[int row] => Second[row];
    }

    private sealed class DateTimeAndInstant : TwoTypedColumn<DateTime, DateTimeOffset>, IColumn<DateTimeOffset>
    {
        public DateTimeAndInstant(DateTime[] dateTimes, DateTimeOffset[] instants)
            : base(dateTimes, instants)
        {
        }

        ReadOnlySpan<DateTimeOffset> IColumn<DateTimeOffset>.Values => Second;

        DateTimeOffset IColumn<DateTimeOffset>.this[int row] => Second[row];
    }

    private sealed class NullableIntAndText : TwoTypedColumn<int?, string>, IColumn<string>
    {
        public NullableIntAndText()
            : base(new int?[] { 1, null }, new[] { "a", "b" })
        {
        }

        ReadOnlySpan<string> IColumn<string>.Values => Second;

        string IColumn<string>.this[int row] => Second[row];
    }

    // A column that implements no IColumn<>.
    private sealed class UntypedColumn : IColumn
    {
        public string Name => "c";

        public string TypeName => null;

        public int RowCount => 2;

        public object GetValue(int row) => row;

        public void Dispose()
        {
        }
    }
