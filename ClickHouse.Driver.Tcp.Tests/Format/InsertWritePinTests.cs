    // The rows { value, null } inserted into one column of the type: the bytes, "refuses" when the gather refuses the
    // null, or "plan" and the exception when the plan refuses the property.
    private static string NullOutcome<T>(string type, T value)
        where T : class
    {
        Block schema = PocoWritePlanTests.SchemaOf(PocoWritePlanTests.Target("value", type));
        PocoWritePlan<Row<T>> plan;
        try
        {
            plan = PocoWritePlan<Row<T>>.Build(PocoTypeDescriptor<Row<T>>.Build(), schema);
        }
        catch (Exception e)
        {
            return "plan " + e.GetType().Name;
        }

        var rows = new[] { new Row<T> { Value = value }, new Row<T> { Value = null } };
        using var buffer = PocoRowBuffer<Row<T>>.Create(rows, "rows", rows.Length, CancellationToken.None);
        using PocoInsertSource<Row<T>> source = plan.CreateSource(buffer, rows.Length);
        try
        {
            source.Gather(0, rows.Length);
        }
        catch (InvalidOperationException e) when (e.Message.Contains("cannot hold null", StringComparison.Ordinal))
        {
            return "refuses";
        }

        return Convert.ToHexString(PocoWritePlanTests.Insert(schema, source));
    }

    private static async Task<string> OutcomeAsync(PinCase pin, int start)
    {
        IColumn column = await pin.Column();
        try
        {
            IColumnCodec codec = ConverterHarness.Codec(pin.Type);
            InsertColumnWrite write;
            try
            {
                write = InsertColumnWrite.For(codec, column, pin.Type, ConverterHarness.Context, ConverterDerivation.Default);
            }
            catch (Exception e)
            {
                return "plan " + e.GetType().Name;
            }

            if (write is null)
            {
                return "refused";
            }

            try
            {
                return Convert.ToHexString(await WriteAsync(write, column, start, column.RowCount - start));
            }
            catch (Exception e)
            {
                return e.GetType().Name;
            }
        }
        finally
        {
            column.Dispose();
        }
    }

    private static Task<byte[]> WriteAsync(InsertColumnWrite write, IColumn column, int start, int length)
        => CodecTestHarness.WriteAsync(w =>
        {
            IColumnWriteState state = write.Begin(column, start, length);
            try
            {
                write.WritePrefix(w, column, start, length, state);
                write.Write(w, column, start, length, state);
            }
            finally
            {
                state?.Dispose();
            }
        });

